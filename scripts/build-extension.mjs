// Builds the browser extension: generates fingerprint.js from the engine's own describe function
// (so recorded steps match what the engine replays), renders the icons, and zips the result.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ext = join(root, 'extension');
const { describeScript } = await import(join(root, 'dist/page-scripts.js'));

writeFileSync(join(ext, 'fingerprint.js'),
  '// Generated by scripts/build-extension.mjs from src/page-scripts.ts. Do not edit.\n' +
  `self.flintrailDescribe = ${describeScript.toString()};\n`);

// Icons are committed; pass --icons to render them again from icons/icon.svg with Chromium.
if (process.argv.includes('--icons') || !existsSync(join(ext, 'icons/128.png'))) {
  const { chromium } = await import('playwright-core');
  const browser = await chromium.launch({ executablePath: process.env.FLINTRAIL_CHROME || undefined });
  const svg = readFileSync(join(ext, 'icons/icon.svg'), 'utf8');
  for (const size of [16, 32, 48, 128]) {
    const page = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 });
    await page.setContent(`<style>html,body{margin:0;background:transparent}svg{width:${size}px;height:${size}px;display:block}</style>${svg}`);
    await page.screenshot({ path: join(ext, 'icons', `${size}.png`), omitBackground: true });
    await page.close();
  }
  await browser.close();
}

if (process.argv.includes('--zip')) {
  const { version } = JSON.parse(readFileSync(join(ext, 'manifest.json'), 'utf8'));
  const zip = join(root, `flintrail-extension-${version}.zip`);
  rmSync(zip, { force: true });
  execFileSync('zip', ['-qr', zip, '.', '-x', 'icons/icon.svg'], { cwd: ext });
  console.log(`extension packed: ${zip}`);
}
console.log('extension built');
