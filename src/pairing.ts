// Automatic pairing with the browser extension. At startup Rocketwright registers a native messaging host
// (com.soflution.flintrail) in every Chromium browser installed for this user. The extension asks it for
// the relay token, so connecting a browser needs no copy-paste. Only the Rocketwright extension IDs
// may talk to the host (extensionIds in profiles.ts): the browser checks allowed_origins before starting it.
import { chmodSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { config } from './config.js';
import { extensionIds, knownBrowsers } from './profiles.js';

export const HOST_NAME = 'com.soflution.flintrail';

/** Writes the host launcher script, with the settings this process uses baked in. */
function writeLauncher(): string {
  const hostScript = join(dirname(fileURLToPath(import.meta.url)), 'native-host.js');
  const launcher = join(config.home, 'native-host');
  const quote = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;
  const env = [
    `ROCKETWRIGHT_HOME=${quote(config.home)}`,
    `ROCKETWRIGHT_RELAY_PORT=${quote(String(config.relayPort))}`,
    ...(process.env.ROCKETWRIGHT_TOKEN ? [`ROCKETWRIGHT_TOKEN=${quote(process.env.ROCKETWRIGHT_TOKEN)}`] : []),
    // The browsers whose profiles the host may look up (tests point it at their own browser only).
    ...(process.env.ROCKETWRIGHT_PAIRING_DIRS ? [`ROCKETWRIGHT_PAIRING_DIRS=${quote(process.env.ROCKETWRIGHT_PAIRING_DIRS)}`] : []),
  ];
  mkdirSync(config.home, { recursive: true });
  writeFileSync(launcher, `#!/bin/sh\n# Generated by Rocketwright: answers the extension's pairing request.\nexport ${env.join(' ')}\nexec ${quote(process.execPath)} ${quote(hostScript)}\n`, { mode: 0o700 });
  chmodSync(launcher, 0o700);
  return launcher;
}

/**
 * Registers the native messaging host in every installed browser (and in the extra user data
 * directories given, e.g. a dedicated automation profile). Returns the directories written to.
 */
export function installNativeHost(extraDataDirs: string[] = []): string[] {
  if (process.env.ROCKETWRIGHT_PAIRING === 'off') return [];
  const dirs = [...knownBrowsers().map((b) => b.dataDir), ...extraDataDirs].filter((d) => d && existsSync(d));
  if (!dirs.length) return [];
  const launcher = writeLauncher();
  const manifest = JSON.stringify({
    name: HOST_NAME,
    description: 'Rocketwright: pairs the browser extension with the local Rocketwright relay.',
    path: launcher,
    type: 'stdio',
    allowed_origins: extensionIds().map((id) => `chrome-extension://${id}/`),
  }, null, 2);
  const written: string[] = [];
  for (const dir of dirs) {
    const target = join(dir, 'NativeMessagingHosts');
    try {
      mkdirSync(target, { recursive: true });
      writeFileSync(join(target, `${HOST_NAME}.json`), manifest);
      written.push(dir);
    } catch (e) {
      console.error(`rocketwright: could not register pairing in ${dir}: ${(e as Error).message}`);
    }
  }
  return written;
}
